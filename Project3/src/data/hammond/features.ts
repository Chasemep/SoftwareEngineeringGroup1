import type { CampusFeature, PointCoordinates, PolygonCoordinates } from '../../models/campus'

function rectangleFromCenter(
  [lat, lng]: PointCoordinates,
  latRadius: number,
  lngRadius: number,
): PolygonCoordinates {
  return [
    [lat + latRadius, lng - lngRadius],
    [lat + latRadius, lng + lngRadius],
    [lat - latRadius, lng + lngRadius],
    [lat - latRadius, lng - lngRadius],
  ]
}

function rectangleFromAnchors(
  anchorA: PointCoordinates,
  anchorB: PointCoordinates,
  latRadius: number,
  lngPadding: number,
): PolygonCoordinates {
  const centerLat = (anchorA[0] + anchorB[0]) / 2
  const westLng = Math.min(anchorA[1], anchorB[1]) - lngPadding
  const eastLng = Math.max(anchorA[1], anchorB[1]) + lngPadding

  return [
    [centerLat + latRadius, westLng],
    [centerLat + latRadius, eastLng],
    [centerLat - latRadius, eastLng],
    [centerLat - latRadius, westLng],
  ]
}

